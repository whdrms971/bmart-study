-- Delivery 도메인 소유 데이터 (PostgreSQL / H2 PostgreSQL 모드 호환)

create table rider (
    id                 varchar(40) primary key,
    display_name       varchar(80) not null,
    duty_status        varchar(30) not null,
    last_lat           double precision,
    last_lng           double precision,
    last_location_at   timestamp with time zone,
    last_seen_at       timestamp with time zone,
    version            bigint not null default 0
);

create table delivery (
    id                    varchar(40) primary key,
    order_id              varchar(40) not null,
    customer_id           varchar(40) not null,
    mfc_id                varchar(40) not null,
    source_system         varchar(40) not null,
    request_id            varchar(100) not null,
    request_hash          varchar(64) not null,
    status                varchar(30) not null,
    location_mode         varchar(20) not null,
    rider_id              varchar(40),
    assignment_version    integer not null default 0,
    dest_lat              double precision not null,
    dest_lng              double precision not null,
    dest_address          varchar(300) not null,
    dest_address_detail   varchar(200),
    origin_lat            double precision not null,
    origin_lng            double precision not null,
    total_weight_grams    integer,
    expected_package_count integer not null,
    packages_ready        boolean not null default false,
    customer_note         varchar(300),
    dispatch_note         varchar(200),
    dispatch_stalled      boolean not null default false,
    created_at            timestamp with time zone not null,
    updated_at            timestamp with time zone not null,
    picked_up_at          timestamp with time zone,
    delivered_at          timestamp with time zone,
    cancelled_at          timestamp with time zone,
    version               bigint not null default 0,
    constraint uq_delivery_request unique (source_system, request_id)
);
create index ix_delivery_order on delivery(order_id);
create index ix_delivery_status on delivery(status);
create index ix_delivery_rider on delivery(rider_id);

create table delivery_package (
    package_id      varchar(60) primary key,
    delivery_id     varchar(40) not null references delivery(id),
    status          varchar(30) not null,
    handover_id     varchar(60),
    handed_over_rider_id varchar(40),
    handed_over_at  timestamp with time zone,
    last_error      varchar(200),
    updated_at      timestamp with time zone not null
);
create index ix_package_delivery on delivery_package(delivery_id);

create table dispatch_attempt (
    id            varchar(40) primary key,
    delivery_id   varchar(40) not null references delivery(id),
    attempt_no    integer not null,
    status        varchar(20) not null,
    reason        varchar(200),
    created_at    timestamp with time zone not null,
    closed_at     timestamp with time zone,
    constraint uq_attempt_no unique (delivery_id, attempt_no)
);

create table dispatch_offer (
    id            varchar(40) primary key,
    attempt_id    varchar(40) not null references dispatch_attempt(id),
    delivery_id   varchar(40) not null references delivery(id),
    rider_id      varchar(40) not null references rider(id),
    status        varchar(20) not null,
    viewed        boolean not null default false,
    offered_at    timestamp with time zone not null,
    expires_at    timestamp with time zone not null,
    responded_at  timestamp with time zone,
    reason        varchar(200),
    version       bigint not null default 0
);
create index ix_offer_rider on dispatch_offer(rider_id, status);
create index ix_offer_delivery on dispatch_offer(delivery_id);

create table delivery_status_history (
    id           bigint generated by default as identity primary key,
    delivery_id  varchar(40) not null,
    from_status  varchar(30),
    to_status    varchar(30) not null,
    actor        varchar(60) not null,
    reason       varchar(300),
    at           timestamp with time zone not null
);
create index ix_history_delivery on delivery_status_history(delivery_id);

-- 위치 원천 이력. source(DEVICE_GPS / SIMULATED_ROUTE)와 scenario_id로 테스트·실GPS를 분리 조회
create table rider_location (
    id            bigint generated by default as identity primary key,
    delivery_id   varchar(40) not null,
    rider_id      varchar(40) not null,
    source        varchar(20) not null,
    scenario_id   varchar(40),
    seq           bigint not null,
    lat           double precision,
    lng           double precision,
    accuracy_m    double precision,
    speed_mps     double precision,
    heading       double precision,
    measured_at   timestamp with time zone,
    received_at   timestamp with time zone not null,
    verdict       varchar(30) not null,
    reason        varchar(200)
);
create index ix_location_delivery on rider_location(delivery_id, source, seq);

create table delivery_latest_location (
    delivery_id   varchar(40) primary key,
    rider_id      varchar(40) not null,
    source        varchar(20) not null,
    scenario_id   varchar(40),
    seq           bigint not null,
    lat           double precision not null,
    lng           double precision not null,
    accuracy_m    double precision,
    measured_at   timestamp with time zone not null,
    received_at   timestamp with time zone not null
);

create table delivery_eta (
    delivery_id       varchar(40) primary key,
    status            varchar(20) not null,
    provider          varchar(30),
    eta_seconds       integer,
    distance_meters   integer,
    computed_at       timestamp with time zone,
    last_attempt_at   timestamp with time zone,
    last_error        varchar(200)
);

create table delivery_proof (
    id             varchar(40) primary key,
    delivery_id    varchar(40) not null references delivery(id),
    rider_id       varchar(40) not null,
    request_id     varchar(100) not null,
    method         varchar(30) not null,
    photo_path     varchar(300) not null,
    photo_sha256   varchar(64) not null,
    photo_bytes    bigint not null,
    note           varchar(300),
    distance_to_destination_m double precision,
    created_at     timestamp with time zone not null,
    constraint uq_proof_delivery unique (delivery_id)
);

create table outbox_event (
    event_id        varchar(40) primary key,
    event_type      varchar(60) not null,
    aggregate_id    varchar(40) not null,
    payload         varchar(4000) not null,
    created_at      timestamp with time zone not null,
    published_at    timestamp with time zone,
    attempts        integer not null default 0,
    next_attempt_at timestamp with time zone not null,
    last_error      varchar(300)
);
create index ix_outbox_pending on outbox_event(published_at, next_attempt_at);

-- (sourceSystem, requestId) 명령 멱등
create table idempotency_record (
    source_system   varchar(40) not null,
    request_id      varchar(100) not null,
    request_hash    varchar(64) not null,
    response_body   varchar(4000) not null,
    created_at      timestamp with time zone not null,
    primary key (source_system, request_id)
);

-- (sourceSystem, eventId) 이벤트 1회 적용
create table inbox_event (
    source_system   varchar(40) not null,
    event_id        varchar(100) not null,
    event_type      varchar(60) not null,
    applied_at      timestamp with time zone not null,
    primary key (source_system, event_id)
);
